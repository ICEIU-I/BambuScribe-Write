package engine

// The common science-symbol row uses continuous curves for loops and bowls,
// and straight rules for operators. Keep the existing advances in both fonts.
func addScienceSymbols(put func(string, float64, ...Stroke)) {
	put("α", 7,
		symbolEllipse(3.2, 5.4, 2.3, 2.6),
		symbolCurve(Stroke{{5.3, 2.8}, {5.05, 4.9}, {5.05, 7.9}, {5.8, 8.8}}))
	put("β", 7, symbolCurve(Stroke{
		{1.5, 9.5}, {1.55, 7.1}, {1.5, 5}, {1.7, 3.2},
		{1.8, 2.1}, {2.4, 1.4}, {3.4, 1.4},
		{4.6, 1.4}, {5.4, 2}, {5.4, 3.15},
		{5.4, 4.5}, {3.9, 5.1}, {2.2, 5.2},
		{4.5, 5.05}, {5.8, 5.65}, {5.8, 7.1},
		{5.8, 8.3}, {4.7, 9}, {3.35, 9},
		{2.6, 9}, {2.05, 8.65}, {1.7, 8.2},
	}))
	put("γ", 7, symbolCurve(Stroke{
		{.8, 2.6}, {1.05, 2.25}, {1.32, 2}, {1.7, 2},
		{2.8, 2}, {3.5, 6.2}, {3.7, 7.8},
		{3.9, 9}, {3.45, 9.5}, {3.15, 9.5},
		{2.92, 9.5}, {2.8, 9.1}, {2.8, 8.65},
		{2.8, 7.5}, {4.7, 4.2}, {5.6, 2.8},
		{5.87, 2.4}, {6.13, 2.15}, {6.4, 2},
	}))
	put("Δ∆", 7, Stroke{{.7, 9}, {3.5, 1.2}, {6.3, 9}, {.7, 9}})
	put("ΩΩ", 8,
		Stroke{{.7, 8.8}, {2.5, 8.8}},
		symbolCurve(Stroke{
			{2.5, 8.8}, {1.25, 7.9}, {.7, 6.7}, {.7, 5.3},
			{.7, 3}, {1.8, 1.2}, {3.8, 1.2},
			{5.8, 1.2}, {6.9, 3}, {6.9, 5.3},
			{6.9, 6.7}, {6.35, 7.9}, {5.1, 8.8},
		}), Stroke{{5.1, 8.8}, {6.9, 8.8}})
	put("μµ", 4,
		symbolCurve(Stroke{{.5, 3.5}, {.3, 5.4}, {.15, 7.5}, {0, 9}}),
		symbolCurve(Stroke{
			{.5, 3.5}, {.4, 5.2}, {.15, 7.2}, {1.2, 7.2},
			{2.25, 7.2}, {2.95, 4.8}, {3.3, 3.5},
			{3.1, 4.7}, {2.5, 7.3}, {3.3, 7.3},
			{3.55, 7.3}, {3.8, 7.05}, {4, 6.8},
		}))
	put("×", 4, Stroke{{0, 3}, {4, 7}}, Stroke{{0, 7}, {4, 3}})
	put("÷", 4, Stroke{{0, 5}, {4, 5}}, symbolEllipse(2, 2.7, .1, .1), symbolEllipse(2, 7.3, .1, .1))
	put("±", 4, Stroke{{0, 4}, {4, 4}}, Stroke{{2, 2}, {2, 6}}, Stroke{{0, 8}, {4, 8}})
	put("−－", 5, Stroke{{.8, 5.5}, {5.2, 5.5}})
	wave := func(y float64) Stroke {
		return symbolCurve(Stroke{
			{.8, y + .5}, {1.3, y + .5}, {1.7, y}, {2.3, y},
			{3, y}, {4.7, y + 1}, {5.5, y + 1},
			{6.15, y + 1}, {6.65, y + .5}, {7.2, y + .5},
		})
	}
	put("≈", 8, wave(3.1), wave(5.2))
	put("≠", 7, Stroke{{.7, 3.9}, {6.3, 3.9}}, Stroke{{.7, 6.6}, {6.3, 6.6}}, Stroke{{.9, 8.2}, {6.1, 1.8}})
	put("≤", 7, Stroke{{6.2, 2.5}, {1, 4.65}, {6.2, 6.8}}, Stroke{{1, 8.5}, {6.4, 8.5}})
	put("≥", 7, Stroke{{.8, 2.5}, {6, 4.65}, {.8, 6.8}}, Stroke{{.8, 8.5}, {6.4, 8.5}})
	put("∞", 8, symbolCurve(Stroke{
		{4, 5.5}, {5.25, 3.85}, {5.6, 3.3}, {6.05, 3.3},
		{7.6, 3.3}, {7.6, 7.7}, {6.05, 7.7},
		{5.6, 7.7}, {5.25, 7.15}, {4, 5.5},
		{2.75, 3.85}, {2.4, 3.3}, {1.95, 3.3},
		{.4, 3.3}, {.4, 7.7}, {1.95, 7.7},
		{2.4, 7.7}, {2.75, 7.15}, {4, 5.5},
	}))
	put("→", 8, Stroke{{1, 5.5}, {6.6, 5.5}}, Stroke{{5, 4.2}, {6.6, 5.5}, {5, 6.8}})
	degree := symbolEllipse(.7, 2.05, .7, .55)
	put("°", 1.4, degree)
	put("℃", 5.5, degree, symbolCurve(Stroke{
		{5.5, 3}, {5.1, 2.6}, {4.8, 2.4}, {4.3, 2.4},
		{3.1, 2.4}, {2.4, 3.7}, {2.4, 5.1},
		{2.4, 6.6}, {3.1, 7.8}, {4.3, 7.8},
		{4.8, 7.8}, {5.15, 7.55}, {5.5, 7.2},
	}))
	put("′", 2, Stroke{{1.5, 2}, {.5, 5.5}})
	put("″", 3.5, Stroke{{1.3, 2}, {.3, 5.5}}, Stroke{{2.8, 2}, {1.8, 5.5}})
}
